#!/usr/bin/env bash
# Generate the GATE bundle for an EXTERNAL artifact repo: the reviewer core, the
# deterministic checker and the threat-model validator, so all three lanes that
# guard the paved road can also guard an artifact repo's pull requests.
#
#   ./scripts/vendor_reviewer.sh /path/to/artifact-repo
#
# Inside this repo nothing is ever vendored: the PR workflow puts agent/ on
# PYTHONPATH and imports the one core. A separate artifact repo cannot do that,
# so it gets a GENERATED copy plus a manifest recording the exact source commit
# and a hash per file. The artifact repo's own workflow re-checks that manifest,
# so a hand-edited copy fails its build instead of silently reviewing with a
# different reviewer than the one this repo tests.
#
# A vendored copy that drifted 100 lines is what made a seat report an error
# message that had already been deleted from the core - hence the manifest.
set -euo pipefail

SRC="$(cd "$(dirname "$0")/.." && pwd)"
DEST="${1:?usage: vendor_reviewer.sh /path/to/artifact-repo}"
OUT="$DEST/pr-reviewer"

[ -d "$DEST/.git" ] || { echo "not a git repo: $DEST" >&2; exit 1; }

mkdir -p "$OUT/reviewer" "$OUT/deterministic" "$OUT/threat-model"
cp "$SRC/agent/reviewer/"*.py "$OUT/reviewer/"
cp "$SRC/pr-surface/pr-reviewer/review_pr.py" "$OUT/"
cp "$SRC/.reviewer.yaml" "$DEST/.reviewer.yaml"
# The artifact's PR runs all THREE lanes, so the deterministic checker and the
# threat-model validator are pinned here too. Only the tooling travels - the
# artifact keeps its OWN threat-model/app.tc.json and boundaries.yaml at its
# root, because the model describes that app, not this one.
cp "$SRC/deterministic/checks.py"       "$OUT/deterministic/"
cp "$SRC/deterministic/rules.guard"     "$OUT/deterministic/"
cp "$SRC/threat-model/validate.py"      "$OUT/threat-model/"

REV="$(git -C "$SRC" rev-parse HEAD)"
{
  echo "# GENERATED by scripts/vendor_reviewer.sh - do not edit by hand."
  echo "# Re-run the script against the paved-road repo to update."
  echo "source_repo: aws-samples/sample-agentic-cicd-gates"
  echo "source_commit: $REV"
  echo "generated_at: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "files:"
  for f in "$OUT/reviewer/"*.py "$OUT/review_pr.py" \
           "$OUT/deterministic/checks.py" "$OUT/deterministic/rules.guard" \
           "$OUT/threat-model/validate.py" "$DEST/.reviewer.yaml"; do
    printf '  %s: %s\n' "${f#"$DEST"/}" "$(shasum -a 256 "$f" | cut -d' ' -f1)"
  done
} > "$OUT/VENDOR_MANIFEST.yaml"

echo "vendored the reviewer core into $OUT"
echo "  source commit : ${REV:0:8}"
echo "  files         : $(ls -1 "$OUT/reviewer/"*.py | wc -l | tr -d ' ') reviewer module(s) + review_pr.py"
echo "                  + deterministic/{checks.py,rules.guard} + threat-model/validate.py + .reviewer.yaml"
echo "  manifest      : $OUT/VENDOR_MANIFEST.yaml"
echo
echo "Add to the artifact repo's workflow so drift fails ITS build:"
echo "    python pr-reviewer/verify_vendor.py"
